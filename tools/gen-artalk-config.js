'use strict';
/* Generates /data/artalk.yml from environment variables.
   - SQLite by default (file lives on the /data volume)
   - set ARTALK_DB_TYPE + DATABASE_URL to use PostgreSQL/MySQL instead
   - first-run admin: set ARTALK_ADMIN_EMAIL + ARTALK_ADMIN_PASSWORD,
     otherwise register the first admin from the dashboard login page */
const fs = require('fs');
const crypto = require('crypto');
const bcrypt = require('bcryptjs');

const DATA = '/data';
const KEY_FILE = DATA + '/artalk-app-key';
const CFG_FILE = DATA + '/artalk.yml';

let appKey = '';
try { appKey = fs.readFileSync(KEY_FILE, 'utf8').trim(); } catch (e) {}
if (!appKey) {
  appKey = crypto.randomBytes(32).toString('hex');
  fs.writeFileSync(KEY_FILE, appKey);
}

const domain = process.env.RAILWAY_PUBLIC_DOMAIN || '';
const siteUrl = process.env.ARTALK_SITE_URL || (domain ? 'https://' + domain : '');
const siteDefault = process.env.ARTALK_SITE_DEFAULT || 'My Hexo Blog';

const trusted = [];
if (siteUrl) trusted.push(siteUrl);
(process.env.ARTALK_TRUSTED_DOMAINS || '').split(/\s+/).filter(Boolean).forEach(function (d) { trusted.push(d); });

const dbType = process.env.ARTALK_DB_TYPE || 'sqlite';

const lines = [];
lines.push('# generated by docker-entrypoint.sh - edit env vars, not this file');
lines.push('host: 127.0.0.1');
lines.push('port: 23366');
lines.push('app_key: "' + appKey + '"');
lines.push('debug: false');
lines.push('locale: ' + (process.env.ARTALK_LOCALE || 'en'));
lines.push('timezone: ' + (process.env.ARTALK_TIMEZONE || 'UTC'));
lines.push('site_default: "' + siteDefault + '"');
lines.push('site_url: "' + siteUrl + '"');
lines.push('login_timeout: 259200');
lines.push('db:');
lines.push('  type: ' + dbType);
if (dbType === 'sqlite') {
  lines.push('  file: /data/artalk.db');
} else {
  const u = new URL(process.env.DATABASE_URL || '');
  lines.push('  name: ' + (u.pathname.replace(/^\//, '') || 'artalk'));
  lines.push('  host: ' + u.hostname);
  lines.push('  port: ' + (u.port || (dbType === 'mysql' ? '3306' : '5432')));
  lines.push('  user: ' + decodeURIComponent(u.username || 'root'));
  lines.push('  password: "' + decodeURIComponent(u.password || '') + '"');
  const sslmode = u.searchParams.get('sslmode') || 'require';
  lines.push('  ssl: ' + (sslmode === 'disable' ? 'false' : 'true'));
}
lines.push('http:');
lines.push('  body_limit: 100');
lines.push('  proxy_header: "X-Forwarded-For"');
lines.push('log:');
lines.push('  enabled: true');
lines.push('  filename: /data/artalk.log');
lines.push('cache:');
lines.push('  enabled: false');
lines.push('  type: builtin');
lines.push('  expires: 30');
lines.push('trusted_domains:');
if (trusted.length) {
  trusted.forEach(function (t) { lines.push('  - "' + t + '"'); });
} else {
  lines.push('  - ""');
}
lines.push('img_upload:');
lines.push('  enabled: true');
lines.push('  path: /data/artalk-img/');
lines.push('  max_size: 20');
lines.push('  public_path: /comment/static/images/');
lines.push('moderator:');
lines.push('  pending_default: false');
lines.push('  api_fail_block: true');
const email = process.env.ARTALK_ADMIN_EMAIL || '';
const pass = process.env.ARTALK_ADMIN_PASSWORD || '';
if (email && pass) {
  lines.push('admin_users:');
  lines.push('  - name: "' + (process.env.ARTALK_ADMIN_NAME || 'admin') + '"');
  lines.push('    email: "' + email + '"');
  lines.push('    password: "(bcrypt)' + bcrypt.hashSync(pass, 10) + '"');
  lines.push('    badge_name: Administrator');
  lines.push('    badge_color: "#0083FF"');
}
fs.writeFileSync(CFG_FILE, lines.join('\n') + '\n');
console.log('[artalk] config written to ' + CFG_FILE + ' (db=' + dbType + ')');